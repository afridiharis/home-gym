#!/usr/bin/env python3
"""Build FORGE → index.html + manifest.webmanifest + sw.js (GitHub Pages serves the repo root).

- Inlines the VectorCraft icon sprite (design/icons-src/*.svg → <symbol id="i-NAME">, currentColor)
- Inlines the tower illustration (assets/tower.svg) with station groups turned into themeable classes
- Writes an ASSETS manifest so the app only references files that exist
- Concatenates CSS + JS in dependency order (no bundler, no dependencies)
Run:  python3 tools/build.py
"""
import hashlib, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

CSS = ["src/styles/tokens.css", "src/styles/app.css"]
JS = ["src/data.js", "src/tower.js", "src/demos.js", "src/guard.js", "src/core.js", "@generated",
      "src/ui/kit.js", "src/ui/today.js", "src/ui/player.js", "src/ui/progress.js", "src/ui/moves.js",
      "src/ui/me.js", "src/ui/onboard.js", "src/ui/sheets.js", "src/ui/main.js"]


def sprite():
    out = []
    for fn in sorted(os.listdir("design/icons-src")):
        if not fn.endswith(".svg"):
            continue
        name = fn[:-4]
        svg = open(f"design/icons-src/{fn}").read()
        inner = re.search(rf'<g id="{re.escape(name)}">(.*?)</g>\s*</g>', svg, re.S).group(1)
        inner = re.sub(r'stroke="#[0-9a-fA-F]{6}"', 'stroke="currentColor"', inner)
        inner = re.sub(r'fill="#[0-9a-fA-F]{6}"', 'fill="currentColor"', inner)
        inner = re.sub(r"\s+", " ", inner).strip()
        out.append(f'<symbol id="i-{name}" viewBox="0 0 64 64">{inner}</symbol>')
    return f'<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">{"".join(out)}</svg>', len(out)


def tower_svg():
    svg = open("assets/tower.svg").read()
    svg = re.sub(r"<\?xml[^>]*>\s*", "", svg)
    svg = re.sub(r"<title>.*?</title>", "", svg, flags=re.S)
    svg = re.sub(r' width="\d+(pt)?" height="\d+(pt)?"', "", svg, count=1)
    svg = svg.replace('id="frame"', 'class="tw-frame"')
    for st in ("bar", "dips", "knee", "push", "floor"):
        svg = svg.replace(f'id="st-{st}"', f'class="tw-{st}"')
    svg = re.sub(r'\s(?:id|data-name)="Layer_1"', "", svg)
    svg = re.sub(r'stroke="#[0-9a-fA-F]{6}"', 'class="s"', svg)
    svg = re.sub(r'fill="#[0-9a-fA-F]{6}"', 'class="f"', svg)
    svg = svg.replace('fill="none" class="s"', 'fill="none" class="s"')
    # an element can't carry two class attributes: merge "class="f" ... class="s""
    svg = re.sub(r'class="(f|s)"([^>]*?)class="(f|s)"', r'class="\1 \3"\2', svg)
    svg = re.sub(r"\s+", " ", svg).strip()
    return svg


def brand_svg(path, cls):
    svg = open(path).read()
    svg = re.sub(r"<\?xml[^>]*>\s*", "", svg)
    svg = re.sub(r"<title>.*?</title>", "", svg, flags=re.S)
    svg = re.sub(r"#142033", "currentColor", svg, flags=re.I)
    svg = svg.replace("<svg", f'<svg class="{cls}" role="img" aria-label="FORGE"', 1)
    return re.sub(r"\s+", " ", svg).strip()


def jpeg_size(path):
    """Width and height from a JPEG's SOF marker (stdlib only)."""
    b = open(path, "rb").read()
    i = 2
    while i < len(b):
        marker, size = b[i + 1], int.from_bytes(b[i + 2:i + 4], "big")
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            return int.from_bytes(b[i + 7:i + 9], "big"), int.from_bytes(b[i + 5:i + 7], "big")
        i += 2 + size
    raise ValueError(f"no SOF in {path}")


def assets():
    a = {"celebrate": None, "celebrateStill": None, "drawing": None, "poster": None, "clips": {}, "photos": {}}
    for p in ("assets/motion/celebrate.webp", "assets/motion/celebrate.png", "assets/motion/celebrate.gif"):
        if os.path.exists(p):
            a["celebrate"] = p
            break
    if os.path.exists("assets/motion/celebrate-still.png"):
        a["celebrateStill"] = "assets/motion/celebrate-still.png"
    if os.path.exists("assets/tower-drawing.svg"):
        a["drawing"] = "assets/tower-drawing.svg"
    if os.path.exists("print/forge-wall-chart.pdf"):
        a["poster"] = "print/forge-wall-chart.pdf"
    if os.path.isdir("assets/clips"):
        for fn in sorted(os.listdir("assets/clips")):
            if fn.endswith(".mp4"):
                a["clips"][fn[:-4]] = f"assets/clips/{fn}"
    if os.path.isdir("assets/photos"):
        for fn in sorted(os.listdir("assets/photos")):
            stem, ext = os.path.splitext(fn)
            if ext.lower() in (".jpg", ".jpeg", ".webp", ".avif"):
                ph = a["photos"].setdefault(stem, {})
                ph[ext.lower().lstrip(".").replace("jpeg", "jpg")] = f"assets/photos/{fn}"
                if ext.lower() in (".jpg", ".jpeg"):
                    ph["w"], ph["h"] = jpeg_size(f"assets/photos/{fn}")
    return a


def main():
    spr, n_icons = sprite()
    tower = tower_svg()
    ast = assets()
    generated = (f"/* generated by tools/build.py */\nconst TOWER_SVG = {json.dumps(tower)};\n"
                 f"const LOGO_SVG = {json.dumps(brand_svg('assets/brand/logo.svg', 'brand-lockup'))};\n"
                 f"const MARK_SVG = {json.dumps(brand_svg('assets/brand/mark.svg', 'brand-mark'))};\n"
                 f"const ASSETS = {json.dumps(ast)};\n")
    css = "\n".join(open(f).read() for f in CSS)
    js = "\n".join(generated if f == "@generated" else open(f).read() for f in JS)
    version = hashlib.sha1((css + js + spr).encode()).hexdigest()[:10]

    head_icons = []
    if os.path.exists("assets/icons/apple-touch-icon.png"):
        head_icons.append('<link rel="apple-touch-icon" href="assets/icons/apple-touch-icon.png">')
    if os.path.exists("assets/icons/favicon.ico"):
        head_icons.append('<link rel="icon" href="assets/icons/favicon.ico" sizes="16x16 32x32 48x48">')
    if os.path.exists("assets/icons/favicon-32.png"):
        head_icons.append('<link rel="icon" type="image/png" sizes="32x32" href="assets/icons/favicon-32.png">')
    head_icons.append('<link rel="icon" type="image/svg+xml" href="assets/brand/mark.svg">')
    og = ""
    if os.path.exists("assets/og.png"):
        og = ('<meta property="og:title" content="FORGE — back-safe strength at home">'
              '<meta property="og:description" content="A friendly strength and rehab plan for your power tower.">'
              '<meta property="og:image" content="https://afridiharis.github.io/home-gym/assets/og.png">'
              '<meta name="twitter:card" content="summary_large_image">')

    html = f"""<!doctype html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>FORGE</title>
<meta name="description" content="Back-safe strength training for your power tower: one clear next step, forgiving streaks, split days with research-backed limits.">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="apple-mobile-web-app-title" content="FORGE">
<meta name="theme-color" media="(prefers-color-scheme: light)" content="#F4F6FA">
<meta name="theme-color" media="(prefers-color-scheme: dark)" content="#0E1320">
<link rel="manifest" href="manifest.webmanifest">
{chr(10).join(head_icons)}
{og}
<style>
{css}
</style>
</head>
<body>
{spr}
<main id="app" aria-live="polite"></main>
<script>
"use strict";
const FORGE_VERSION = "{version}";
{js}
</script>
</body>
</html>
"""
    open("index.html", "w").write(html)

    icons = []
    for size, path, purpose in ((192, "assets/icons/icon-192.png", "any"), (512, "assets/icons/icon-512.png", "any"),
                                (512, "assets/icons/icon-maskable-512.png", "maskable")):
        if os.path.exists(path):
            icons.append({"src": path, "sizes": f"{size}x{size}", "type": "image/png", "purpose": purpose})
    manifest = {"name": "FORGE — home gym", "short_name": "FORGE", "start_url": "./", "scope": "./", "display": "standalone",
                "background_color": "#F4F6FA", "theme_color": "#F4F6FA", "orientation": "portrait", "icons": icons}
    open("manifest.webmanifest", "w").write(json.dumps(manifest, indent=1))

    cache = ["./", "index.html", "manifest.webmanifest", "assets/brand/logo.svg", "assets/brand/mark.svg"]
    for d in ("assets/audio", "assets/icons", "assets/motion", "assets/photos"):
        if os.path.isdir(d):
            cache += [f"{d}/{f}" for f in sorted(os.listdir(d)) if not f.startswith(".")]
    for p in (ast["drawing"], ast["celebrate"]):
        if p:
            cache.append(p)
    sw = f"""/* FORGE service worker — generated by tools/build.py (version {version}).
   Network-first for the page (updates land immediately), cache-first for assets. */
const CACHE = "forge-{version}";
const PRECACHE = {json.dumps(sorted(set(cache)))};
self.addEventListener("install", (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener("fetch", (e) => {{
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  const isPage = req.mode === "navigate" || req.url.endsWith("/") || req.url.endsWith("index.html");
  if (isPage) {{
    e.respondWith(fetch(req).then((r) => {{ const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); return r; }})
      .catch(() => caches.match(req).then((r) => r || caches.match("index.html"))));
    return;
  }}
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fetch(req).then((r) => {{
    if (r.ok) {{ const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }}
    return r;
  }})));
}});
"""
    open("sw.js", "w").write(sw)
    print(f"built index.html ({len(html):,} B, {n_icons} icons, version {version}); manifest ({len(icons)} icons); sw.js ({len(set(cache))} precached)")
    print("assets:", json.dumps({k: (v if not isinstance(v, dict) else len(v)) for k, v in ast.items()}))


if __name__ == "__main__":
    main()
